#!/usr/bin/env python
"""Render reference-audit-2026-11-11.md (the tables) and corrections-lines.md from list.json, the spec, the evidence file and
the delta. Offline; every number in the output is read from those files, never typed.

  python -I render_audit.py --audit > reference-audit-2026-11-11.md
  python -I render_audit.py --corrections > corrections-lines.md      # rows to paste into CORRECTIONS.md
"""
import json, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.dont_write_bytecode = True
sys.path.insert(0, str(HERE))
import d1303a_spec as S  # noqa: E402

LIST = {r["id"]: r for r in json.loads((HERE / "list.json").read_text(encoding="utf-8"))["rows"]}
EV = json.loads((HERE / "fetch-evidence-2026-11-11.json").read_text(encoding="utf-8"))
DELTA = json.loads((HERE / "delta-2026-11-11.json").read_text(encoding="utf-8"))
FETCH = {x["url"]: x for x in EV["other_fetches"] + EV["checked_pages"]}
AUDIT = "[`reference-audit-2026-11-11.md`](docs/audits/reference-audit-2026-11-11/reference-audit-2026-11-11.md)"


def fetched(url):
    x = FETCH.get(url)
    if not x:
        return "not fetched"
    st = x["status"]
    if st == 200:
        return f"HTTP 200, title \"{(x.get('title') or '').strip()[:70].replace('|', '/')}\""
    if st == "robots-refused":
        return "refused (robots.txt disallowed or unverifiable; fail-closed)"
    return f"HTTP {st}"


def rule_of(rid, url):
    for u, why in LIST[rid]["flagged"]:
        if u == url:
            return why
    if url in ("https://arxiv.org/abs/2103.03874", "https://arxiv.org/abs/2402.06627"):
        return "R2 (arXiv id/title mismatch)"
    return "not flagged itself: sibling background citation (ATLAS footnote [2]) removed with the flagged one, same defect"


def outcome(rid):
    if rid in S.UNVERIFIED:
        return "unverified"
    if rid in S.REPLACE:
        return "fixed (replaced)"
    if rid in S.REMOVE:
        return "fixed (flagged reference removed)"
    return "unchanged (false positive)"


def before(rid, f):
    d = DELTA["rows"].get(rid, {})
    return d.get(f, [None, None])


def audit():
    rows = [r for r in LIST.values() if r["batch"] in (0, 1)]
    p = print
    p("<!-- generated by render_audit.py from list.json, d1303a_spec.py, fetch-evidence-2026-11-11.json, delta-2026-11-11.json; do not hand-edit the tables -->")
    out = {}
    for r in rows:
        out.setdefault(outcome(r["id"]), []).append(r["id"])
    p("## Outcome (the 6 deferred rows + batch 1 of the D130-3 list = %d rows)\n" % len(rows))
    p("| outcome | rows | ids |\n|---|---|---|")
    for k in ("fixed (flagged reference removed)", "fixed (replaced)", "unverified", "unchanged (false positive)"):
        ids = out.get(k, [])
        p(f"| {k} | {len(ids)} | {', '.join(ids)} |")
    p(f"| **total** | **{len(rows)}** | |\n")
    p("## Per-row outcomes\n")
    p("| id | batch | tier before | outcome | flagged URL (rule) -> fetch result 2026-11-11 | change |\n|---|---|---|---|---|---|")
    for r in rows:
        rid = r["id"]
        fl = r["flagged"] or [[u, None] for u in S.REMOVE.get(rid, [])]
        cell = "; ".join(f"`{u}` ({rule_of(rid, u)}) -> {fetched(u)}" for u, _ in fl)
        if rid in S.KEPT:
            cell = "; ".join(f"`{u}` -> {fetched(u)}" for u in S.KEPT[rid]["urls"])
        if rid in S.REMOVE and rid not in LIST or (rid in S.REMOVE and not r["flagged"] and rid != "INC-04207"):
            cell = "; ".join(f"`{u}` -> {fetched(u)}" for u in S.REMOVE[rid])
        if rid == "INC-04207":
            cell = f"`{S.REMOVE[rid][0]}` (R2 arXiv id/title mismatch) -> {fetched(S.REMOVE[rid][0])}"
        if rid in S.KEEP_ALSO:
            cell += "; kept: " + ", ".join(f"`{u}` -> {fetched(u)}" for u in S.KEEP_ALSO[rid])
        if rid in S.UNVERIFIED:
            ch = "`status: unverified` (`no-confirmed-source`); references, title, tier untouched. " + " ".join(S.UNVERIFIED[rid])
        elif rid in S.REPLACE:
            sp = S.REPLACE[rid]
            ch = f"reference -> `{sp['ref']['url']}` (fetched 200, names the incident); " + (
                "title, description" + (", affected" if sp.get("affected") else "") + " re-derived; " if sp.get("description") else "description kept (supported by the page); ") + "demoted to auto"
        elif rid in S.KEPT:
            ch = S.KEPT[rid]["why"]
        else:
            ch = "reference(s) removed; demoted to auto" if DELTA["rows"][rid].get("quality_tier") else "reference(s) removed; already auto"
        t = LIST[rid]["quality_tier"]
        p(f"| {rid} | {r['batch']} | {t} | {outcome(rid)} | {cell} | {ch} |")
    p("")
    p("## Field-level delta (working agreement 2)\n")
    b, a = DELTA["entry_count"]
    p(f"Control = committed data at base {DELTA['base']}; new = this branch's build. Entry count {b} -> {a}; ID set equal: {DELTA['id_set_equal']}; ID order equal: {DELTA['id_order_equal']}; rows with any difference: {len(DELTA['rows'])} (= the {len(S.REMOVE)} remove rows + {len(S.REPLACE)} replace rows + {len(S.UNVERIFIED)} unverified rows); rows outside them with any difference: {len([x for x in DELTA['unintended'] if x[1]=='not a target'])}; unintended field moves: {len(DELTA['unintended'])}.\n")
    p("Envelope / `data/stats.json` keys that moved (declared set; any other key would be a defect, and none moved):\n")
    p("| key | before | after | cause |\n|---|---|---|---|")
    why = {"generated": "build date stamp", "incident_count": "the 2 newly unverified rows leave the count",
           "unverified_count": "the 2 newly unverified rows",
           "landmark_count": "the 6 curated deferred rows leave the landmark tier by demotion (D130(c))"}
    for k, (x, y) in DELTA["stats"].items():
        p(f"| `{k}` | {x} | {y} | {why.get(k, '')} |")
    p("")
    fields = {}
    for rid, d in DELTA["rows"].items():
        for f in d:
            fields.setdefault(f, []).append(rid)
    kind = {"updated": ("derived", "history stamp: content changed (build date)"),
            "last_seen": ("derived", "history stamp: content changed (build date)"),
            "references": ("intended", "the D130-3a change itself"),
            "quality_tier": ("intended", "ruling D130(c): every row whose reference is replaced or removed demotes to auto; never promoted. INC-03292 was already auto"),
            "confidence": ("derived", "`_derive_confidence`: curated/reviewed -> high; 2+ sources with a CVE stay high, 2+ sources or a CVE/CVSS give medium. Follows quality_tier only"),
            "tier": ("derived", "`_derive_tier`: curated -> landmark, so the 6 curated deferred rows (no aiid_id, corpus not ai-harm) become feed. Follows quality_tier only"),
            "discovery_method": ("intended", "landmark-only label (integrity check): its override line is dropped for INC-04207 (D139(b)) and for INC-02471, INC-02871 (same mechanism, same reason; see Declared knock-ons)"),
            "status": ("intended", "D130(b): unverified"),
            "status_reason": ("intended", "{code: no-confirmed-source, as_of: 2026-11-11}"),
            "title": ("intended", "re-derived from the confirmed source so title and description agree (bounce lesson iii)"),
            "description": ("intended", "re-derived from the confirmed source; claims the source does not support dropped"),
            "affected": ("intended", "INC-03212: package names the source does not name dropped")}
    p("| field | rows | kind | justification |\n|---|---|---|---|")
    for f, ids in sorted(fields.items()):
        k, j = kind[f]
        lst = f" ({', '.join(ids)})" if len(ids) <= 6 else ""
        p(f"| `{f}` | {len(ids)}{lst} | {k} | {j} |")
    p("")
    tiers = [rid for rid, d in DELTA["rows"].items() if "tier" in d]
    p(f"`tier` landmark -> feed on {len(tiers)} rows: {', '.join(tiers)}. `landmark_count` {DELTA['stats']['landmark_count'][0]} -> {DELTA['stats']['landmark_count'][1]}. INC-02076 (reviewed) is demoted but stays landmark through its `aiid_id`.")
    conf = [rid for rid, d in DELTA["rows"].items() if "confidence" in d]
    p(f"\n`confidence` moved on {len(conf)} rows ({', '.join(c + ' ' + str(DELTA['rows'][c]['confidence'][0]) + '->' + str(DELTA['rows'][c]['confidence'][1]) for c in conf)}).")
    p("\nFull per-row before/after: `delta-2026-11-11.json`.")


def corrections():
    for r in LIST.values():
        rid = r["id"]
        if r["batch"] not in (0, 1) or rid in S.KEPT:
            continue
        d = DELTA["rows"][rid]
        t = LIST[rid]["quality_tier"]
        if rid in S.UNVERIFIED:
            print(f"| 2026-11-11 | `{rid}` marked `status: unverified` (`no-confirmed-source`, D130-3a) | `status`, `status_reason`, `updated`, `last_seen`; references, title and `quality_tier` ({t}) untouched; the row leaves `incident_count` | Its only reference is a publisher index page (R1) and no source naming the incident was found after the documented effort. Agent-suggested, pending user re-review. | {AUDIT} (row `{rid}`) |")
            continue
        fields = [f for f in ("references", "title", "description", "affected") if f in d]
        dem = f"`quality_tier` {t} -> auto (D130(c))" if "quality_tier" in d else "`quality_tier` already auto"
        derived = [f"`{f}`" for f in ("confidence", "tier") if f in d]
        dm = ", `discovery_method` cleared (landmark-only label, D139(b))" if "discovery_method" in d else ""
        verb = "reference replaced" + (", title and description re-derived" if "description" in d else "") if rid in S.REPLACE else "flagged reference removed"
        urls = S.REMOVE.get(rid) or [S.REPLACE[rid]["old"]]
        why = "; ".join(f"{u}: {rule_of(rid, u)}, {fetched(u)}" for u in urls)
        keep = ("It was the row's only reference; the replacement was written only from a page fetched through `ingest/common.py` that names the incident."
                if rid in S.REPLACE else "The row keeps its other references.")
        print(f"| 2026-11-11 | `{rid}` {verb} (D130-3a) | {', '.join(fields)}{dm}; {dem}; derived {', '.join(derived) + ', ' if derived else ''}`updated`, `last_seen` | Not a source for the incident ({why}). {keep} Agent-suggested, pending user re-review. | {AUDIT} (row `{rid}`) |")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8", newline="\n")
    audit() if "--audit" in sys.argv else corrections()
