"""wilson_ci.py -- N9 precision audit: Wilson 95% intervals from HUMAN labels only.

Reads the review sheet written by ``scripts/precision_sample.py`` and the
sampling frame next to it, and computes precision (share of rows labelled
``in-scope``) per tier, per stratum and overall, each with a Wilson score
95% interval.

What it reads, and what it never reads
--------------------------------------
Only the ``id``, ``human_label`` and ``human_by`` columns. The
``suggested_label`` / ``suggested_reason`` / ``suggested_by`` columns and
``agent_suggestions.json`` are agent suggestions, not measurements, and no
code path in this module reads them (``read_human_labels`` builds its rows
from the three human columns only). With only suggestions filled, the result
is ``status: pending`` and the CLI prints "no human labels".

A ``human_label`` is accepted only with a non-empty ``human_by`` that does not
name an agent/model (``AGENT_LIKE``): an agent cannot fill the human column
on the user's behalf and have it counted.

Two treatments of ``unsure``
----------------------------
* ``excluding_unsure`` -- unsure rows are dropped from numerator and
  denominator.
* ``strict`` -- unsure rows count as NOT in scope (a lower bound).
Both are always reported; neither is silently preferred.

Weighting back to the population
--------------------------------
Allocation is proportional WITHIN a tier but the two tiers are sampled at
different fractions (100 of the feed, 50 of the landmark set), and rounding
makes even within-tier weights slightly unequal. So every estimate is the
stratified estimator

    p = sum_h (N_h / N) * (x_h / n_h)

over the strata h that have at least one counted row (N_h = stratum
population from frame.json, n_h = counted labelled rows, x_h = in-scope
rows). Strata with no counted rows are left out of N and their population is
reported as ``unrepresented_population`` -- never imputed. The interval is a
Wilson score interval evaluated at p with Kish's effective sample size
``n_eff = (sum w_i)^2 / sum w_i^2`` (w_i = N_h / n_h per counted row), the
standard way to carry a design weight into a binomial interval. With equal
weights this reduces exactly to the textbook Wilson interval on x/n (tested).
Per-stratum figures are unweighted (one stratum = one weight).
Per-``quality_tier`` figures (``by_quality_tier``, within each tier) are
domain estimates in ratio form (``_domain_estimate``): quality_tier is an
implicit stratifier only, so domain sizes are random within a stratum; each
is flagged ``small_n`` below 30 rows and should be read as indicative.

Usage
-----
    python scripts/wilson_ci.py                      # print + write results.json
    python scripts/wilson_ci.py --render-datasheet   # also rewrite the DATASHEET block
    python scripts/wilson_ci.py --check              # exit 1 if results.json / DATASHEET are stale
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRECISION_ROOT = ROOT / "docs" / "audits" / "precision"
DATASHEET = ROOT / "docs" / "DATASHEET.md"
RESULTS_FILE = "results.json"
SHEET_FILE = "review_sheet.csv"
FRAME_FILE = "frame.json"
SAMPLE_FILE = "sample.json"

Z95 = 1.959963984540054
LABELS = ("in-scope", "out-of-scope", "unsure")
AGENT_LIKE = re.compile(
    r"(?<![a-z])(agent|claude|anthropic|gpt|openai|llm|model|bot|assistant|ai|automated|script)(?![a-z])", re.I
)
BLOCK_BEGIN = "<!-- precision:begin (generated by scripts/wilson_ci.py --render-datasheet; do not hand-edit) -->"
BLOCK_END = "<!-- precision:end -->"


class LabelError(ValueError):
    """A human column is filled in a way that cannot be counted."""


def wilson(x: float, n: float, z: float = Z95) -> tuple[float, float]:
    """Wilson score interval for a binomial proportion x/n (no continuity
    correction). x and n may be non-integer (effective counts)."""
    if n <= 0:
        raise ValueError("n must be positive")
    p = x / n
    z2 = z * z
    denom = 1 + z2 / n
    centre = (p + z2 / (2 * n)) / denom
    half = (z / denom) * math.sqrt(max(p * (1 - p) / n + z2 / (4 * n * n), 0.0))
    return max(0.0, centre - half), min(1.0, centre + half)


class AuditDirError(ValueError):
    """The default audit directory is ambiguous (more than one) or absent."""


def sole_audit_dir(root: Path | None = None) -> Path:
    """The ONE audit directory under docs/audits/precision/ (b17 advisory 2).

    This used to pick the newest dated directory, so a second directory --
    including a variant such as ``2026-10-11b`` that a date-shaped glob does
    not even see -- silently became what the CLI measured and rendered, while
    scripts/validate.py kept checking the pinned one. Now ANY second
    subdirectory is an error: pass ``--audit-dir`` explicitly, or (for a new
    audit) take the user decision and re-pin scripts/validate.py first. The
    pin itself lives only in validate.py; this function does not duplicate it,
    and validate.py fails if the sole directory is not the pinned one.
    """
    root = PRECISION_ROOT if root is None else root
    dirs = sorted(p for p in root.iterdir() if p.is_dir()) if root.is_dir() else []
    if not dirs:
        raise AuditDirError(f"no audit directory under {root}")
    if len(dirs) > 1:
        raise AuditDirError(f"{len(dirs)} directories under {root} ({[d.name for d in dirs]}); "
                            "refusing to guess -- pass --audit-dir explicitly")
    return dirs[0]


REQUIRED_SHEET_COLUMNS = ("id", "human_label", "human_by")


def read_sheet(sheet: Path) -> tuple[list[str], list[dict]]:
    """(header, rows) of the review sheet. Tolerates what a spreadsheet
    round-trip does to a CSV: a UTF-8 byte-order mark (read as utf-8-sig, so
    it is not glued onto the first header), CRLF line endings and re-quoted
    fields (the csv module parses both). Raises LabelError if a required
    column is missing or a header still carries a BOM (e.g. a double BOM)."""
    with sheet.open(encoding="utf-8-sig", newline="") as f:
        reader = csv.DictReader(f)
        rows = list(reader)
        header = list(reader.fieldnames or [])
    if any(h.startswith("\ufeff") for h in header):
        raise LabelError(f"{sheet.name}: header carries a byte-order mark after decoding: {header[:1]!r}")
    missing = [c for c in REQUIRED_SHEET_COLUMNS if c not in header]
    if missing:
        raise LabelError(f"{sheet.name}: required column(s) {missing} missing from the header")
    return header, rows


def read_human_labels(sheet: Path) -> dict[str, str]:
    """id -> human label, from the human columns ONLY. Raises LabelError on a
    label without a (non-agent) reviewer, a reviewer without a label, or an
    unknown label."""
    labels: dict[str, str] = {}
    for i, row in enumerate(read_sheet(sheet)[1], 2):
        rid = (row.get("id") or "").strip()
        label = (row.get("human_label") or "").strip().lower()
        by = (row.get("human_by") or "").strip()
        if not label and not by:
            continue
        if not label:
            raise LabelError(f"{sheet.name}:{i} ({rid}): human_by is set but human_label is empty")
        if label not in LABELS:
            raise LabelError(f"{sheet.name}:{i} ({rid}): human_label {label!r} not one of {LABELS}")
        if not by:
            raise LabelError(f"{sheet.name}:{i} ({rid}): human_label without human_by -- "
                             "a label is counted only with the reviewer's name")
        if AGENT_LIKE.search(by):
            raise LabelError(f"{sheet.name}:{i} ({rid}): human_by {by!r} names an agent/model; "
                             "agent suggestions are never counted as human labels")
        labels[rid] = label
    return labels


def sheet_ids(sheet: Path) -> list[str]:
    return [(r.get("id") or "").strip() for r in read_sheet(sheet)[1]]


def _estimate(rows: list[tuple[str, str]], pops: dict[str, int], strict: bool) -> dict:
    """rows: (stratum, label). Stratified estimate + Wilson at Kish n_eff."""
    counted: dict[str, list[int]] = {}
    for stratum, label in rows:
        if label == "unsure" and not strict:
            continue
        counted.setdefault(stratum, []).append(1 if label == "in-scope" else 0)
    reps = {h: v for h, v in counted.items() if v}
    n = sum(len(v) for v in reps.values())
    x = sum(sum(v) for v in reps.values())
    unrep = sum(p for h, p in pops.items() if h not in reps)
    if n == 0:
        return {"n": 0, "in_scope": 0, "precision": None, "ci95": None, "n_eff": None,
                "unrepresented_population": unrep}
    big_n = sum(pops[h] for h in reps)
    p = sum((pops[h] / big_n) * (sum(v) / len(v)) for h, v in reps.items())
    w = [pops[h] / len(v) for h, v in reps.items() for _ in v]
    n_eff = sum(w) ** 2 / sum(wi * wi for wi in w)
    lo, hi = wilson(p * n_eff, n_eff)
    return {
        "n": n, "in_scope": x, "unweighted_precision": round(x / n, 6),
        "precision": round(p, 6), "n_eff": round(n_eff, 2),
        "ci95": [round(lo, 6), round(hi, 6)],
        "unrepresented_population": unrep,
    }


SMALL_N = 30


def _domain_estimate(rows: list[tuple[str, str, str]], pops: dict[str, int], domain: str,
                     strict: bool) -> dict:
    """Domain (e.g. quality_tier) estimate, ratio form: every counted row
    carries its stratum's design weight w = N_h / n_h (n_h = ALL counted rows
    in stratum h, any domain); p_d = sum(w*y over d) / sum(w over d), Wilson at
    Kish n_eff over the domain's weights. Domain sizes inside a stratum are
    random, so this is a post-stratified/ratio estimate, not a stratum figure;
    n < SMALL_N is flagged."""
    counted = [(h, d, lab) for h, d, lab in rows if strict or lab != "unsure"]
    n_h: dict[str, int] = {}
    for h, _, _ in counted:
        n_h[h] = n_h.get(h, 0) + 1
    dom = [(pops[h] / n_h[h], 1 if lab == "in-scope" else 0) for h, d, lab in counted if d == domain]
    if not dom:
        return {"n": 0, "in_scope": 0, "precision": None, "ci95": None, "n_eff": None, "small_n": True}
    sw = sum(wt for wt, _ in dom)
    p = sum(wt * y for wt, y in dom) / sw
    n_eff = sw ** 2 / sum(wt * wt for wt, _ in dom)
    lo, hi = wilson(p * n_eff, n_eff)
    return {"n": len(dom), "in_scope": sum(y for _, y in dom), "precision": round(p, 6),
            "n_eff": round(n_eff, 2), "ci95": [round(lo, 6), round(hi, 6)], "small_n": len(dom) < SMALL_N}


def compute(audit_dir: Path, root: Path = ROOT) -> dict:
    frame = json.loads((audit_dir / FRAME_FILE).read_text(encoding="utf-8"))
    sample = json.loads((audit_dir / SAMPLE_FILE).read_text(encoding="utf-8"))
    labels = read_human_labels(audit_dir / SHEET_FILE)
    stratum_of = {e["id"]: e["stratum"] for e in sample["entries"]}
    qt_of = {e["id"]: str(e.get("quality_tier")) for e in sample["entries"]}
    unknown = sorted(set(labels) - set(stratum_of))
    if unknown:
        raise LabelError(f"human labels for ids not in the sample: {unknown[:5]}")
    pops = {s["stratum"]: s["population"] for s in frame["strata"]}
    total = len(sample["entries"])
    res: dict = {
        "audit_dir": audit_dir.relative_to(root).as_posix() if audit_dir.is_relative_to(root) else audit_dir.as_posix(),
        "audit_date": frame.get("audit_date"),
        "seed": frame.get("seed"),
        "sample_size": total,
        "tier_allocation": frame.get("tier_allocation"),
        "sample_entries_sha256": sample.get("entries_sha256"),
        "method": ("Stratified sample (tier x source family, proportional within tier, seeded systematic draw); "
                   "precision = share labelled in-scope against INCLUSION.md; stratified estimator weighted to "
                   "stratum populations; Wilson score 95% interval at Kish effective n. Human labels only."),
        "human_labelled": len(labels),
    }
    if not labels:
        res["status"] = "pending"
        return res
    res["status"] = "measured" if len(labels) == total else "partial"
    rows = [(stratum_of[i], lab) for i, lab in sorted(labels.items())]
    res["label_counts"] = {lab: sum(1 for _, x in rows if x == lab) for lab in LABELS}
    out = {}
    for treatment, strict in (("excluding_unsure", False), ("strict", True)):
        t = {"overall": _estimate(rows, pops, strict)}
        for tier in sorted({s["tier"] for s in frame["strata"]}):
            tp = {h: p for h, p in pops.items() if h.split("/")[0] == tier}
            t[tier] = _estimate([r for r in rows if r[0] in tp], tp, strict)
        t["per_stratum"] = {
            h: _estimate([r for r in rows if r[0] == h], {h: pops[h]}, strict) for h in sorted(pops)
        }
        t["by_quality_tier"] = {}
        for tier in sorted({s["tier"] for s in frame["strata"]}):
            tp = {h: p for h, p in pops.items() if h.split("/")[0] == tier}
            trows = [(stratum_of[i], qt_of[i], lab) for i, lab in sorted(labels.items()) if stratum_of[i] in tp]
            for qt in sorted({d for _, d, _ in trows}):
                t["by_quality_tier"][f"{tier}/{qt}"] = _domain_estimate(trows, tp, qt, strict)
        out[treatment] = t
    res["estimates"] = out
    return res


def _fmt(e: dict) -> str:
    if not e or e.get("precision") is None:
        return "no counted labels"
    lo, hi = e["ci95"]
    return f"{100 * e['precision']:.1f}% (95% CI {100 * lo:.1f}-{100 * hi:.1f}; n={e['n']}, n_eff={e['n_eff']})"


def render_block(res: dict) -> str:
    alloc = res.get("tier_allocation") or {}
    head = (f"Method: {res['method']} Sample: {alloc.get('feed')} feed-tier rows + {alloc.get('landmark')} "
            f"landmark-tier rows, seed {res['seed']}, drawn {res['audit_date']} "
            f"([`{res['audit_dir']}/`]({res['audit_dir'].removeprefix('docs/')}/)).")
    if res["status"] == "pending":
        body = ("**Status: measurement pending.** No human labels have been recorded yet, so this "
                "datasheet states no precision figure. The review sheet carries agent-suggested labels; "
                "those are suggestions for the reviewer, not a measurement, and are not quoted here.")
    elif res["status"] == "partial":
        body = (f"**Status: partial ({res['human_labelled']} of {res['sample_size']} rows human-labelled); "
                "no figure is published until every sampled row is labelled.**")
    else:
        ex, st = res["estimates"]["excluding_unsure"], res["estimates"]["strict"]
        body = "\n".join([
            f"**Status: measured** from {res['human_labelled']} human-labelled rows.",
            "",
            "| Scope | Precision, unsure excluded | Precision, unsure = out (strict) |",
            "|---|---|---|",
            f"| Feed tier | {_fmt(ex.get('feed'))} | {_fmt(st.get('feed'))} |",
            f"| Landmark tier | {_fmt(ex.get('landmark'))} | {_fmt(st.get('landmark'))} |",
            f"| Overall (weighted to population) | {_fmt(ex['overall'])} | {_fmt(st['overall'])} |",
        ])
    return f"{BLOCK_BEGIN}\n{head}\n\n{body}\n\nRe-derive: `python scripts/wilson_ci.py --check`\n{BLOCK_END}"


# b17 advisory 3: a precision figure hand-typed OUTSIDE the generated block.
# "Figure" = a percentage (digits followed by %, a full-width percent sign,
# "percent", "per cent" or "pct", optionally after a space or no-break space)
# or a bare proportion written 0.xx / .xx. The proportion's lookahead rejects
# only a further digit or a dot-then-digit, so a sentence-final "0.92." still
# counts while version strings ("v2.13.0", "0.13.0.") and "CVSS 9.8." do not
# (gate BOUNCE 1 on 26dfcdb4: the old lookahead "(?![0-9.])" let any figure
# followed by a full stop through). Characters outside ASCII are built
# numerically (house rule: no escape literals).
_SPACES = "[" + chr(0x20) + chr(0xA0) + chr(0x202F) + "]*"
_PERCENT = "(?:%|" + chr(0xFF05) + "|percent|per cent|pct)"
FIGURE_RE = re.compile(
    "(?<![0-9A-Za-z.])(?:[0-9]+(?:[.,][0-9]+)?" + _SPACES + _PERCENT + "|0?[.][0-9]+(?![0-9]|[.][0-9]))",
    re.I,
)
_LIST_ITEM_RE = re.compile("^(?:[-*+]|[0-9]+[.)])" + chr(0x20))
MEASURED_HEADING = "## Measured precision"
# What counts as a MENTION of precision (rule 2 below): the word "precision"
# standing alone. A hyphenated compound that starts with it ("precision-first",
# "precision-oriented") describes a design choice, not a measurement, and does
# not count (foreman ruling on the gate's false-positive advisory (a)).
# "imprecision" does not count either.
MENTION_RE = re.compile("(?<![a-z])precision(?![a-z]|-[a-z])", re.I)
SECTION_RULE_HINT = ("figures in this section must be generated; put explanatory text outside the section or "
                     "inside the generated block (i.e. emit it from wilson_ci.render_block)")


def _chunks(text: str) -> list[str]:
    """Blank-line paragraphs; a list paragraph is further split per item (so
    one bullet's percentage is not attributed to another bullet's mention of
    precision). Tables stay whole: a header naming precision and a row
    carrying the number are one unit."""
    out: list[str] = []
    for para in re.split("(?:" + chr(10) + "[" + chr(32) + chr(9) + "]*){2,}", text):
        cur: list[str] = []
        for line in para.split(chr(10)):
            if _LIST_ITEM_RE.match(line) and cur:
                out.append(chr(10).join(cur))
                cur = []
            cur.append(line)
        if cur:
            out.append(chr(10).join(cur))
    return out


def stray_precision_figures(text: str) -> list[str]:
    """Problems for any precision figure in the DATASHEET that the generated
    block did not put there. Rules (each one has a test that makes it fire):
      1. exactly one BLOCK_BEGIN and one BLOCK_END marker (a second, hand-made
         block would otherwise sit unchecked after the first);
      2. outside the block, no paragraph / list item / table that mentions
         precision (MENTION_RE: the standalone word; "precision-first" and
         other "precision-<word>" compounds are not mentions) carries a figure
         (FIGURE_RE);
      3. outside the block, the "## Measured precision" section carries no
         figure at all, whether or not the word appears next to it. This is
         deliberately strict: an EXPLANATORY figure typed into the section's
         prose ("Wilson 95% score intervals", "under 1% of the corpus") is
         flagged too. Figures in that section must come from the generator;
         put such text outside the section or emit it from render_block. The
         generated block already states the interval method ("Wilson score
         95% interval at Kish effective n"), so the prose need not repeat it.
    Known limits (documented, not detected): a bare integer ("precision: 92"),
    a figure spelled in words, a figure separated from the word "precision"
    by a blank line OUTSIDE the Measured-precision section, a figure next to
    only a "precision-<word>" compound OUTSIDE the section, and every file
    other than docs/DATASHEET.md (README, release notes, CHANGELOG)."""
    text = text.replace(chr(13) + chr(10), chr(10))
    problems: list[str] = []
    nb, ne = text.count(BLOCK_BEGIN), text.count(BLOCK_END)
    if (nb, ne) != (1, 1):
        problems.append(f"DATASHEET has {nb} precision:begin and {ne} precision:end markers; exactly one each "
                        "is allowed")
    block = datasheet_block(text)
    outside = text.replace(block, chr(10) + chr(10)) if block else text
    for chunk in _chunks(outside):
        if MENTION_RE.search(chunk):
            for m in FIGURE_RE.finditer(chunk):
                problems.append(f"DATASHEET: figure {m.group(0)!r} next to 'precision' outside the generated "
                                f"block: {chunk.strip()[:120]!r}")
    i = outside.find(MEASURED_HEADING)
    if i >= 0:
        rest = outside[i + len(MEASURED_HEADING):]
        j = rest.find(chr(10) + "## ")
        section = rest if j < 0 else rest[:j]
        for m in FIGURE_RE.finditer(section):
            problems.append(f"DATASHEET: figure {m.group(0)!r} in the '{MEASURED_HEADING[3:]}' section outside "
                            f"the generated block -- {SECTION_RULE_HINT}")
    return sorted(set(problems))


def datasheet_block(text: str) -> str | None:
    i, j = text.find(BLOCK_BEGIN), text.find(BLOCK_END)
    if i < 0 or j < 0 or j < i:
        return None
    return text[i:j + len(BLOCK_END)]


def dump(res: dict) -> str:
    return json.dumps(res, indent=2, ensure_ascii=False) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Wilson 95% precision intervals from human labels only.")
    ap.add_argument("--audit-dir", type=Path, default=None)
    ap.add_argument("--render-datasheet", action="store_true")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--datasheet", type=Path, default=DATASHEET)
    a = ap.parse_args(argv)
    try:
        audit_dir = a.audit_dir or sole_audit_dir()
    except AuditDirError as exc:
        print(f"[wilson] REFUSED: {exc}")
        return 2
    audit_dir = audit_dir.resolve()
    # the repo root that owns this audit dir (<root>/docs/audits/precision/<date>), so the
    # recorded audit_dir is repo-relative wherever the tree lives
    root = audit_dir.parents[3] if audit_dir.parents[1].name == "audits" else ROOT
    try:
        res = compute(audit_dir, root)
    except LabelError as exc:
        print(f"[wilson] REFUSED: {exc}")
        return 2
    if res["status"] == "pending":
        print("[wilson] no human labels: measurement pending (agent suggestions are never counted).")
    else:
        print(f"[wilson] status {res['status']}: {res['human_labelled']}/{res['sample_size']} human-labelled")
        for t in ("excluding_unsure", "strict"):
            for k in ("feed", "landmark", "overall"):
                print(f"  {t:17s} {k:9s} {_fmt(res['estimates'][t].get(k))}")
    results_path = audit_dir / RESULTS_FILE
    block = render_block(res)
    if a.check:
        bad = []
        if not results_path.exists() or results_path.read_text(encoding="utf-8").replace("\r\n", "\n") != dump(res):
            bad.append(f"{results_path.name} differs from a fresh computation")
        ds = a.datasheet.read_text(encoding="utf-8").replace("\r\n", "\n")
        if datasheet_block(ds) != block:
            bad.append("DATASHEET 'Measured precision' block differs from results")
        stray = stray_precision_figures(ds)
        if bad:
            print("[wilson] STALE: " + "; ".join(bad) + " -- run `python scripts/wilson_ci.py --render-datasheet`")
        if stray:
            print("[wilson] HAND-TYPED: " + "; ".join(stray) + " -- remove the figure; only the generated block "
                  "may state precision")
        if bad or stray:
            return 1
        print("[wilson] results.json and DATASHEET block match a fresh computation.")
        return 0
    results_path.write_text(dump(res), encoding="utf-8", newline="\n")
    if a.render_datasheet:
        ds = a.datasheet.read_text(encoding="utf-8").replace("\r\n", "\n")
        cur = datasheet_block(ds)
        if cur is None:
            print(f"[wilson] {a.datasheet} has no precision block markers")
            return 2
        a.datasheet.write_text(ds.replace(cur, block), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
